// Writes backend/seed/extracteurs.sql: the extractors shipped as models (src/extraction/modeles), compiled as the
// editor does, as first versions. A model already in the database with the same source is not added again; a changed
// model becomes the next version of its supplier (ADR 0013).
//   npm run extracteurs:sql
// An operation writes the SQL of its own extractors the same way:
//   npx tsx scripts/extracteurs-sql.ts <output.sql> <source.ts>=<supplier> [<source.ts>=<supplier>…]
import { readFile, writeFile } from 'node:fs/promises'

import ts from 'typescript'

import { compiler } from '../src/extraction/compilation'
import { MOTEUR, REGLAGES_PAR_DEFAUT, REGLAGES_RELEVE_PAR_DEFAUT } from '../src/extraction/contrat'
import { charger, energieDe } from '../src/extraction/moteur'
import { estReleve } from '../src/extraction/moteurReleve'

const [sortie, ...sources] = process.argv.slice(2)
const MODELES = sources.length
  ? sources.map((s) => {
    const [fichier, fournisseur] = s.split('=')
    if (!fichier || !fournisseur) {
      throw new Error(`« ${s} » : <source.ts>=<fournisseur> attendu`)
    }
    return { source: new URL(fichier, `file://${process.cwd()}/`), fournisseur }
  })
  : [
    { source: new URL('../src/extraction/modeles/edf.ts', import.meta.url), fournisseur: 'EDF' },
    { source: new URL('../src/extraction/modeles/engie.ts', import.meta.url), fournisseur: 'ENGIE' },
    { source: new URL('../src/extraction/modeles/credit-mutuel.ts', import.meta.url), fournisseur: 'Crédit Mutuel' },
  ]

const dollar = (text: string) => {
  if (text.includes('$extracteur$')) {
    throw new Error('$extracteur$ dans le code')
  }
  return `$extracteur$${text}$extracteur$`
}
const quote = (text: string) => `'${text.replaceAll('\'', '\'\'')}'`

// SQL text: the apostrophe doubled
const note = sources.length ? "Extracteur de l''exploitation" : "Modèle livré avec l''application"
const out = ['-- Generated by frontend/scripts/extracteurs-sql.ts (colibri-rent-book): do not edit.', '']
for (const { source: fichier, fournisseur } of MODELES) {
  const source = await readFile(fichier, 'utf8')
  const code = compiler(source, ts)
  // A bank statement extractor (ADR 0018) has no energy, and a margin in its settings
  const releve = estReleve(code)
  const energie = releve ? 'NULL' : quote(energieDe(charger(code)))
  const reglages = releve ? REGLAGES_RELEVE_PAR_DEFAUT : REGLAGES_PAR_DEFAUT
  out.push(
    `INSERT INTO fournisseur (nom) VALUES (${quote(fournisseur)}) ON CONFLICT (nom) DO NOTHING;`,
    `INSERT INTO extracteur (fournisseur_id, version, type, energie, reglages, source, code, moteur, note)`,
    `SELECT fo.id, coalesce((SELECT max(version) FROM extracteur WHERE fournisseur_id = fo.id), 0) + 1,`,
    `  ${quote(releve ? 'releve' : 'facture')}, ${energie},`,
    `  ${quote(JSON.stringify(reglages))}, ${dollar(source)},`,
    `  ${dollar(code)},`,
    `  ${MOTEUR}, '${note}'`,
    `FROM fournisseur fo WHERE fo.nom = ${quote(fournisseur)}`,
    `  AND NOT EXISTS (SELECT 1 FROM extracteur e WHERE e.fournisseur_id = fo.id AND e.source = ${dollar(source)});`,
    '',
  )
}
const target = sortie ? new URL(sortie, `file://${process.cwd()}/`) : new URL('../../backend/seed/extracteurs.sql', import.meta.url)
await writeFile(target, out.join('\n'))
console.log(`${target.pathname} : ${MODELES.length} extracteurs`)
